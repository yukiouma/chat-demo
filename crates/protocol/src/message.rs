use chrono::{DateTime, Utc};
use serde::{Deserialize, Serialize};
use ts_rs::TS;
use uuid::Uuid;

/// One entry in a conversation.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, TS)]
#[ts(export, export_to = "protocol.ts")]
pub struct Message {
    pub id: Uuid,
    pub conversation_id: Uuid,
    pub role: MessageRole,
    /// Position within the conversation.
    pub seq: i32,
    pub parts: Vec<MessagePart>,
    /// Denormalised plain text: the concatenation of the message's text parts.
    pub content: String,
    pub status: MessageStatus,
    pub created_at: DateTime<Utc>,
}

/// A message as it arrives from the client, before the server assigns the
/// fields it owns.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, TS)]
#[ts(export, export_to = "protocol.ts")]
pub struct NewMessage {
    /// Generated by the client so its optimistic copy already matches.
    pub id: Uuid,
    pub role: MessageRole,
    pub parts: Vec<MessagePart>,
    #[serde(default)]
    pub status: MessageStatus,
}

/// A message as the desktop app holds it: what is needed to rebuild the
/// model's context, and nothing more.
///
/// The fields the server owns — the conversation, the position, the plain
/// text, the timestamp — are left out on purpose, so the desktop never has
/// to invent values for them.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, TS)]
#[ts(export, export_to = "protocol.ts")]
pub struct HistoryMessage {
    /// The client's id for the message. It is kept if it is a UUID; if it is
    /// not, the server gives the message one of its own.
    pub id: String,
    pub role: MessageRole,
    pub parts: Vec<MessagePart>,
}

#[derive(Debug, Clone, Copy, Serialize, Deserialize, PartialEq, Eq, TS)]
#[ts(export, export_to = "protocol.ts")]
#[serde(rename_all = "snake_case")]
pub enum MessageRole {
    User,
    Assistant,
    /// The conversation's Instructions: written by the application, not said
    /// by anyone, and never shown in the transcript.
    System,
}

#[derive(Debug, Clone, Copy, Serialize, Deserialize, PartialEq, Eq, TS)]
#[ts(export, export_to = "protocol.ts")]
#[serde(rename_all = "snake_case")]
pub enum MessageStatus {
    Sent,
    Error,
    Cancelled,
}

impl Default for MessageStatus {
    fn default() -> Self {
        Self::Sent
    }
}

/// A typed fragment of a message.
///
/// A tool's input and output live in the same part; the UI library expects
/// them together, and rebuilding the model's context splits them again.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, TS)]
#[ts(export, export_to = "protocol.ts")]
#[serde(tag = "type", rename_all = "snake_case")]
pub enum MessagePart {
    Text {
        text: String,
    },
    Reasoning {
        text: String,
    },
    Tool {
        call_id: String,
        name: String,
        input: serde_json::Value,
        output: Option<serde_json::Value>,
        status: ToolStatus,
    },
}

/// The lifecycle of a tool invocation.
#[derive(Debug, Clone, Copy, Serialize, Deserialize, PartialEq, Eq, TS)]
#[ts(export, export_to = "protocol.ts")]
#[serde(rename_all = "snake_case")]
pub enum ToolStatus {
    InputStreaming,
    InputAvailable,
    ApprovalRequested,
    ApprovalResponded,
    OutputAvailable,
    OutputError,
    OutputDenied,
}

impl Message {
    /// The plain text of a message: its text parts, joined.
    pub fn plain_text(parts: &[MessagePart]) -> String {
        parts
            .iter()
            .filter_map(|part| match part {
                MessagePart::Text { text } => Some(text.as_str()),
                _ => None,
            })
            .collect::<Vec<_>>()
            .join("")
    }
}
